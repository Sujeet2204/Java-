class Rectangle
{
    public static void main(String[] args) 
    {
        int length = 8;
        int width = 4;
        
        int area = length*width;
        int peri = 2*(length+width);

        System.out.println("The area of rectangle is : "+area);
        System.out.println("The perimeter of rectangle is : "+peri);

    }
}