class Datatype
{
    public static void main(String args[])
    {
        int age = 23;
        double marks = 98.9;
        char grade = 'A';
        boolean pass = true;
        String Name = "Sujeet";

        System.out.println("Name = "+Name);
        System.out.println("Age = "+age);
        System.out.println("marks = "+marks);
        System.out.println("Grade = "+grade);
        System.out.println("pass = "+pass);
    }
}